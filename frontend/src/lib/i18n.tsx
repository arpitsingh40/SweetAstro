const DICTS: Record<Lang, Dict> = { en: EN, hi: HI, hinglish: HINGLISH };

interface I18nValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: string) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

function detectLang(): Lang {
  const stored = localStorage.getItem("sweetastro_ui_lang");
  if (stored === "en" || stored === "hi" || stored === "hinglish") return stored;
  const nav = (navigator.language || "").toLowerCase();
  if (nav.startsWith("hi")) return "hi";
  return "en";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(detectLang);

  const setLang = (next: Lang) => {
    setLangState(next);
    localStorage.setItem("sweetastro_ui_lang", next);
  };

  const value = useMemo<I18nValue>(() => ({
    lang,
    setLang,
    t: (key: string) => DICTS[lang][key] || EN[key] || key,
  }), [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
